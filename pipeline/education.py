"""Education content built only from KB facts (FuturePlan WP10). Reference for the Kotlin app.

- did_you_know: one item's `impact` text per day, rotating through the KB.
- watch_out_cards: every condition rule with a note ("greasy pizza box: tear off the
  soiled part"), the cases people most often get wrong.
- quiz: one "which bin?" question per day, the four bins of the city as options.

Nothing is generated by Llama, so nothing here can be wrong in a way the KB is not.
Rotation is by day number, not random, so the Python and Kotlin versions agree.
"""

from __future__ import annotations

from pipeline.impact import STREAMS
from pipeline.kb import DEFAULT_CITY, KnowledgeBase


def did_you_know(kb: KnowledgeBase, day: int, language: str = "en") -> dict:
    ids = kb.item_ids
    item_id = ids[day % len(ids)]
    verdict = kb.resolve(item_id, {}, language)
    return {
        "item_id": item_id,
        "heading": kb.message("did_you_know", language),
        "title": verdict.name,
        "text": verdict.impact,
    }


def watch_out_cards(kb: KnowledgeBase, language: str = "en") -> list[dict]:
    cards = []
    for item_id in kb.item_ids:
        for rule in kb.item(item_id).get("condition_rules", []):
            if "note" not in rule["then"]:
                continue
            verdict = kb.resolve(item_id, dict(rule["if"]), language)
            cards.append(
                {
                    "item_id": item_id,
                    "condition": dict(rule["if"]),
                    "title": verdict.name,
                    "stream": verdict.stream,
                    "bin": verdict.bin_colour,
                    "text": verdict.notes[-1],
                }
            )
    return cards


def quiz(kb: KnowledgeBase, day: int, language: str = "en", city_id: str = DEFAULT_CITY) -> dict:
    ids = kb.item_ids
    # A different stride from did_you_know, so the two do not show the same item each day.
    item_id = ids[(day * 7 + 3) % len(ids)]
    verdict = kb.resolve(item_id, {}, language, city_id)
    options = []
    for stream in STREAMS:
        # resolve() of any item gives the city's colour and names; build them directly.
        colour = kb_city_colour(kb, city_id, stream)
        options.append(
            {
                "stream": stream,
                "bin": colour,
                "label": f"{kb_text(kb, 'colours', colour, language)} "
                f"({kb_text(kb, 'streams', stream, language)})",
            }
        )
    return {
        "item_id": item_id,
        "question": kb.message("quiz_which_bin", language).format(item=verdict.name),
        "options": options,
        "answer": verdict.stream,
        "explanation": verdict.impact,
    }


def kb_city_colour(kb: KnowledgeBase, city_id: str, stream: str) -> str:
    return kb.city(city_id)["bin_colours"][stream]


def kb_text(kb: KnowledgeBase, section: str, key: str, language: str) -> str:
    by_lang = kb.strings[section][key]
    return by_lang.get(language, by_lang["en"])
