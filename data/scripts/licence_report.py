"""How much TACO training data each licence policy keeps (data/taco_licences.md).

    uv run python data/scripts/licence_report.py

Counts images and object instances per KB class under each policy of prepare.py
(--licences all / known / odbl), and which classes still reach `min_instances` (classes
below it are left out of training). Reads only the annotations; nothing is copied.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from data.scripts.prepare import (  # noqa: E402
    LICENCE_POLICIES,
    coco_boxes,
    label_map,
    licence_ok,
    load_taxonomy,
)

ANN = REPO / "data" / "raw" / "taco" / "annotations.json"
OUT = REPO / "data" / "taco_licences.md"


def counts(coco: dict, taxonomy: dict, policy: str) -> tuple[int, Counter]:
    mapping = label_map(taxonomy, "taco", [c["name"] for c in coco["categories"]])
    boxes, _ = coco_boxes(coco, mapping)
    images, instances = 0, Counter()
    for img in coco["images"]:
        if not licence_ok(img, policy) or not boxes[img["id"]]:
            continue
        images += 1
        instances.update(b.cls for b in boxes[img["id"]])
    return images, instances


def main() -> int:
    coco = json.loads(ANN.read_text(encoding="utf-8"))
    taxonomy = load_taxonomy()
    min_n = taxonomy.get("min_instances", 1)
    per = {p: counts(coco, taxonomy, p) for p in LICENCE_POLICIES}
    licences = Counter(str(img.get("license")) for img in coco["images"])
    classes = sorted({c for _, inst in per.values() for c in inst}, key=lambda c: -per["all"][1][c])

    lines = [
        "# TACO data under each licence policy",
        "",
        "Generated by `uv run python data/scripts/licence_report.py` from "
        "`data/raw/taco/annotations.json`. Choose the policy with `prepare.py --licences` "
        "(and `LICENCES` in `models/vision/train.ipynb`).",
        "",
        "Image licence field in TACO: "
        + ", ".join(f"{k}: {v}" for k, v in licences.most_common())
        + f" (of {len(coco['images'])} images).",
        "",
        "| Policy | Images with KB objects | Instances | Classes with >= "
        f"{min_n} instances (trained) |",
        "|---|---|---|---|",
    ]
    for p in LICENCE_POLICIES:
        images, inst = per[p]
        trained = sum(1 for c in inst if inst[c] >= min_n)
        lines.append(f"| `{p}` | {images} | {sum(inst.values())} | {trained} |")
    lines += ["", "Instances per class (classes below the threshold are not trained):", ""]
    lines += ["| Class | " + " | ".join(f"`{p}`" for p in LICENCE_POLICIES) + " |",
              "|---|" + "---|" * len(LICENCE_POLICIES)]  # fmt: skip
    for c in classes:
        cells = []
        for p in LICENCE_POLICIES:
            n = per[p][1][c]
            cells.append(f"{n}" if n >= min_n else f"{n} (left out)")
        lines.append(f"| {c} | " + " | ".join(cells) + " |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:14]))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
